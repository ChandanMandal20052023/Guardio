# -*- coding: utf-8 -*-
"""Import mock CSV data into the Django database.

This script reads ``users.csv`` and ``transactions.csv`` generated by ``generate_data.py``
and populates the corresponding Django models:

* ``users.models.User`` – custom user model.
* ``cards.models.CardProfile`` – credit‑card profile linked to the user.
* ``transactions.models.Transaction`` – transaction records.

The script can be executed with:

```
python backend/ml_model/import_data.py
```

Make sure the PostgreSQL container is running and the Django migrations have been applied
(e.g. ``python manage.py migrate``) before invoking the script.
"""

import os
import csv
import sys
from datetime import datetime

# ---------------------------------------------------------------------------
# Django bootstrap
# ---------------------------------------------------------------------------
# The project root (where ``manage.py`` lives) is two levels up from this file.
PROJECT_ROOT = os.path.abspath(os.path.join(__file__, "..", "..", ".."))
sys.path.append(PROJECT_ROOT)
os.environ.setdefault("DJANGO_SETTINGS_MODULE", "backend.settings")
import django

django.setup()
# ---------------------------------------------------------------------------
# Model imports
# ---------------------------------------------------------------------------
from users.models import User
from cards.models import CardProfile
from transactions.models import Transaction, TransactionStatus

# ---------------------------------------------------------------------------
# Helper constants / defaults
# ---------------------------------------------------------------------------
USERS_CSV = os.path.join(os.path.dirname(__file__), "users.csv")
TRANSACTIONS_CSV = os.path.join(os.path.dirname(__file__), "transactions.csv")

# Placeholder values for fields that are not present in the CSV.
DEFAULT_EXPIRY_MONTH = 12
DEFAULT_EXPIRY_YEAR = 2030
DEFAULT_EMAIL_DOMAIN = "example.com"

def import_users(csv_path: str):
    """Create ``User`` and ``CardProfile`` instances from ``users.csv``.

    The CSV columns are:
        user_id,first_name,last_name,pan_card,phone_number,city,state,
        card_number,card_network,credit_limit,issuing_bank
    """
    created = 0
    with open(csv_path, newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            user_id = row["user_id"].strip()
            email = f"{user_id.lower()}@{DEFAULT_EMAIL_DOMAIN}"
            # ``get_or_create`` ensures idempotency – running the script twice won't duplicate rows.
            user, _ = User.objects.get_or_create(
                user_id=user_id,
                defaults={
                    "first_name": row["first_name"].strip(),
                    "last_name": row["last_name"].strip(),
                    "pan_card": row["pan_card"].strip(),
                    "phone_number": row["phone_number"].strip(),
                    "city": row["city"].strip(),
                    "state": row["state"].strip(),
                    "email": email,
                },
            )
            # ``set_unusable_password`` prevents authentication errors when the user is created.
            if not user.password:
                user.set_unusable_password()
                user.save()

            # Card profile – ``user`` may already have a card from a previous run.
            CardProfile.objects.get_or_create(
                card_number=row["card_number"].strip(),
                defaults={
                    "user": user,
                    "card_network": row["card_network"].strip(),
                    "issuing_bank": row["issuing_bank"].strip(),
                    "credit_limit": float(row["credit_limit"]),
                    "available_credit": float(row["credit_limit"]),
                    "expiry_month": DEFAULT_EXPIRY_MONTH,
                    "expiry_year": DEFAULT_EXPIRY_YEAR,
                },
            )
            created += 1
    print(f"✅ Imported/updated {created} users and card profiles.")


def import_transactions(csv_path: str):
    """Create ``Transaction`` instances from ``transactions.csv``.

    The CSV columns are:
        transaction_id,user_id,card_number,timestamp,merchant,amount_inr,location,is_fraud
    """
    created = 0
    with open(csv_path, newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            user = User.objects.filter(user_id=row["user_id"].strip()).first()
            if not user:
                print(f"⚠️  Skipping transaction {row['transaction_id']}: user not found.")
                continue
            card = CardProfile.objects.filter(card_number=row["card_number"].strip()).first()
            # Determine status from the ``is_fraud`` flag.
            status = (
                TransactionStatus.FRAUD if row["is_fraud"].strip() == "1" else TransactionStatus.SAFE
            )
            # Parse timestamp (CSV uses ``YYYY‑MM‑DD HH:MM:SS``).
            try:
                ts = datetime.strptime(row["timestamp"].strip(), "%Y-%m-%d %H:%M:%S")
            except ValueError:
                print(f"⚠️  Invalid timestamp for {row['transaction_id']}: {row['timestamp']}")
                continue
            Transaction.objects.get_or_create(
                transaction_id=row["transaction_id"].strip(),
                defaults={
                    "user": user,
                    "card": card,
                    "card_number": row["card_number"].strip(),
                    "timestamp": ts,
                    "merchant": row["merchant"].strip(),
                    "amount_inr": float(row["amount_inr"]),
                    "location": row["location"].strip(),
                    "status": status,
                },
            )
            created += 1
    print(f"✅ Imported/updated {created} transactions.")


def main():
    if not os.path.exists(USERS_CSV):
        print(f"❌ Users CSV not found at {USERS_CSV}")
        sys.exit(1)
    if not os.path.exists(TRANSACTIONS_CSV):
        print(f"❌ Transactions CSV not found at {TRANSACTIONS_CSV}")
        sys.exit(1)
    import_users(USERS_CSV)
    import_transactions(TRANSACTIONS_CSV)
    print("🎉 All mock data has been loaded into the database.")

if __name__ == "__main__":
    main()
